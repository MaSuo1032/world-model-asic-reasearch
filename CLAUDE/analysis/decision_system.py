"""Concrete instance of GPT/04's recommended system:
policy proposes K candidates -> latent world model scores them -> execute best.

Policy  : pi0 (best-of-K: the 10-step action expert runs with batch K over one shared prefix)
Scorer  : V-JEPA 2-AC (encode current + goal frame once, roll each candidate H=2 steps, I=1 round)

Also instantiates GPT/05's formula  C_decision ~ I*K*H*U*C_transition  with real model shapes.

    cd CLAUDE && python analysis/decision_system.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from models import (WORKLOADS, HW, SIGLIP_SO400M, GEMMA_2B, GEMMA_300M,  # noqa: E402
                    VJEPA2_G, VJEPA2_AC)
from perf_model import Pass, Workload  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
THOR, H100 = HW[2], HW[0]


def policy(K):
    return Workload(f"pi0 best-of-{K}", "VLA-flow", "K chunks", [
        Pass(SIGLIP_SO400M, "ViT x3", 256, 256, batch=3),
        Pass(GEMMA_2B, "VLM prefill", 816, 816, write_kv=True),
        Pass(GEMMA_300M, "expert x10 (batch K)", 51, 867, kv_cached=816, repeat=10, batch=K)])


def scorer(K, H=2, I=1):
    passes = [Pass(VJEPA2_G, "encode ctx+goal", 256, 256, batch=2)]
    for h in range(1, H + 1):
        passes.append(Pass(VJEPA2_AC, f"rollout h={h}", 258 * h, 258 * h, batch=K, repeat=I,
                           attn_frac=0.5 if h == 1 else 0.75))
    return Workload(f"V-JEPA2-AC score K={K}", "WM-JEPA", "K scores", passes)


out = ["# Policy-proposal + world-model-scoring system (auto-generated by analysis/decision_system.py)\n"]

# --- 1. GPT/05 formula with a real transition model
vj = next(w for w in WORKLOADS if w.name.startswith("V-JEPA"))
I, K, H, U = 10, 400, 2, 1
pred = vj.passes[1].flops() + vj.passes[2].flops()
out.append("## 1. `C_decision ≈ I·K·H·U·C_transition` instantiated with V-JEPA 2-AC\n")
out.append(f"- Settings from `vjepa2/notebooks/utils/world_model_wrapper.py`: I={I}, K={K}, H={H}, U={U} "
           f"→ {I*K*H*U:,} transitions per decision.")
out.append(f"- Predictor FLOPs per decision: {pred/1e12:,.0f} TFLOP → **{pred/(I*K*H*U)/1e9:,.0f} GFLOP per transition** "
           f"(h=1: {vj.passes[1].flops()/(I*K)/1e9:,.0f}, h=2: {vj.passes[2].flops()/(I*K)/1e9:,.0f}; "
           "frame-causal predictor re-processes earlier frames).")
out.append("- GPT/05's illustrative value is 40 MFLOP per transition (compact latent). A token-based latent "
           "(256 tokens × 1024-d per frame) costs **~6,000× more** per transition.")
out.append(f"- Candidate state slice (K=400, S=258, D=1024, BF16): {400*258*1024*2/2**20:,.0f} MiB — "
           "GPT/05's 128-token row (64 MiB) is the right order of magnitude for this class.\n")

# --- 2. policy + scorer sweep
out.append("## 2. pi0 best-of-K proposals + V-JEPA 2-AC scoring (H=2, I=1)\n")
out.append("| K | pi0 ms (Thor) | expert AI | scorer ms (Thor) | total Thor ms | total H100 ms |")
out.append("|---|---|---|---|---|---|")
for k in (1, 2, 4, 8, 16, 32, 64):
    p, s = policy(k), scorer(k)
    e = p.passes[2]
    out.append(f"| {k} | {p.roofline_latency(THOR)*1e3:.1f} | {e.flops()/e.total_bytes(2, 2):,.0f} | "
               f"{s.roofline_latency(THOR)*1e3:.1f} | {(p.roofline_latency(THOR)+s.roofline_latency(THOR))*1e3:.1f} | "
               f"{(p.roofline_latency(H100)+s.roofline_latency(H100))*1e3:.1f} |")
out.append("\nBecause the action expert is weight-bandwidth-bound at K=1 (AI ≈ 60), sampling 16 candidate chunks "
           "costs only ~25% more policy time on Thor: the extra candidates ride on weight reads that were "
           "happening anyway. The scorer then dominates beyond K≈16.\n")

with open(os.path.join(ROOT, "results", "decision_system.md"), "w") as fh:
    fh.write("\n".join(out) + "\n")
print("\n".join(out))
