"""Sensitivity studies that matter for accelerator design.

    python analysis/sensitivity.py
"""
import copy
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from models import WORKLOADS, HW  # noqa: E402
from perf_model import Hardware  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES, FIG = os.path.join(ROOT, "results"), os.path.join(ROOT, "figures")
WL = {w.name: w for w in WORKLOADS}
THOR, H100 = HW[2], HW[0]
out = ["# Sensitivity studies (auto-generated by analysis/sensitivity.py)\n"]


def tbl(h, rows):
    s = ["| " + " | ".join(h) + " |", "|" + "---|" * len(h)]
    s += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(s) + "\n"


# ---------------------------------------------------------------- 1. precision
out.append("## 1. Weight/compute precision on Jetson AGX Thor\n")
out.append("Peak scales 2x per halving of precision (BF16 -> FP8 -> FP4); activations kept at the same width as weights except FP4 (FP8 activations).\n")
rows = []
for name in ["pi0 (3B)", "pi0-FAST (3B)", "OpenVLA (7.5B)", "SmolVLA (0.45B)", "GR00T N1.7 (3B)",
             "Matrix-Game 2.0 (1.3B, streaming)", "DreamZero WAM (14B)", "Llama-3.1-8B decode b=1 ctx=8K"]:
    w = WL[name]
    r = [name]
    for bpw, bpa, mult in ((2, 2, 1), (1, 1, 2), (0.5, 1, 4)):
        hw = Hardware("t", THOR.peak_flops * mult, THOR.bw)
        r.append(f"{w.roofline_latency(hw, bpw, bpa) * 1e3:,.1f}")
    r.append(f"{w.unit_period_s * 1e3:,.0f}" if w.unit_period_s else "–")
    rows.append(r)
out.append(tbl(["Workload", "BF16 ms", "FP8 ms", "FP4 ms", "Budget ms"], rows))

# ---------------------------------------------------------------- 2. denoising steps
out.append("## 2. Flow-matching / diffusion step count (pi0 on Thor, BF16)\n")
steps_rows, steps_x, steps_y_base, steps_y_sram = [], [], [], []
pi0 = WL["pi0 (3B)"]
for k in (1, 2, 4, 5, 10, 20):
    w = copy.deepcopy(pi0)
    w.passes[2].repeat = k
    t = w.roofline_latency(THOR) * 1e3
    # SRAM-resident expert: weights fetched once, reused across k steps
    w2 = copy.deepcopy(w)
    e = w2.passes[2]
    fl, by = e.flops(), e.total_bytes(2, 2) - e.weight_bytes(2) * (k - 1) / k
    t_e = max(fl / THOR.peak_flops, by / THOR.bw)
    t2 = (sum(max(p.flops() / THOR.peak_flops, p.total_bytes(2, 2) / THOR.bw) for p in w2.passes[:2]) + t_e) * 1e3
    steps_rows.append([k, f"{t:.1f}", f"{t2:.1f}", f"{e.weight_bytes(2) / e.total_bytes(2, 2) * 100:.0f}%"])
    steps_x.append(k); steps_y_base.append(t); steps_y_sram.append(t2)
out.append(tbl(["Steps", "Latency ms (weights re-read every step)", "Latency ms (expert weights held on-chip)",
                "Weight share of expert traffic"], steps_rows))

# ---------------------------------------------------------------- 3. context length (LLM) vs fixed
out.append("## 3. KV traffic vs context: LLM grows linearly, VLA prefix is fixed by sensor config\n")
rows = []
for ctx in (2048, 8192, 32768, 131072):
    kv_mb = 2 * 32 * ctx * 8 * 128 * 2 / 1e6
    rows.append([f"{ctx:,}", f"{kv_mb:,.0f}", f"{kv_mb / (15011 + kv_mb) * 100:.0f}%"])
out.append(tbl(["Llama-3.1-8B context", "KV read per token (MB)", "KV share of per-token traffic"], rows))
out.append("pi0 reads its 816-token prefix cache (15 MB) 10x per chunk = 150 MB, vs 6.2 GB of expert weights.\n")

# ---------------------------------------------------------------- 4. what fits on-chip
out.append("## 4. Working sets vs on-chip SRAM\n")
rows = []
for name in ["SmolVLA (0.45B)", "GR00T N1.7 (3B)", "pi0 (3B)", "Matrix-Game 2.0 (1.3B, streaming)", "DreamZero WAM (14B)"]:
    w = WL[name]
    hot = max(p.weight_bytes(1) / p.repeat for p in w.passes if p.repeat > 1) if any(p.repeat > 1 for p in w.passes) else 0
    rows.append([name, f"{hot / 1e6:,.0f}", f"{hot / 2e6:,.0f}", f"{w.resident_state_bytes / 1e6:,.1f}"])
out.append(tbl(["Workload", "Looped-stage weights @FP8 (MB)", "@FP4 (MB)", "Resident cache BF16 (MB)"], rows))
out.append("The *looped stage* (action expert / DiT / video denoiser) is re-executed every step; if its weights fit on-chip the "
           "step loop becomes compute-bound instead of DRAM-bound.\n")

with open(os.path.join(RES, "sensitivity.md"), "w") as fh:
    fh.write("\n".join(out))

import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
fig, ax = plt.subplots(figsize=(7.5, 4.5), facecolor=SURF)
ax.set_facecolor(SURF)
ax.plot(steps_x, steps_y_base, "-o", color="#2a78d6", lw=2, ms=8, mec=SURF, mew=1.5)
ax.plot(steps_x, steps_y_sram, "-s", color="#eb6834", lw=2, ms=8, mec=SURF, mew=1.5)
ax.text(steps_x[-1] + 0.4, steps_y_base[-1], "weights re-read\nevery step", color=INK, va="center", fontsize=8)
ax.text(steps_x[-1] + 0.4, steps_y_sram[-1], "expert weights\nheld on-chip", color=INK, va="center", fontsize=8)
ax.set_xlabel("flow-matching steps"); ax.set_ylabel("roofline latency per chunk (ms)")
ax.set_title("pi0 on Jetson AGX Thor (BF16): the step loop is a weight-streaming problem", loc="left", fontsize=9, color=INK)
ax.grid(True, color=GRID, lw=0.6)
for sp in ("top", "right"):
    ax.spines[sp].set_visible(False)
ax.set_xlim(0, 25)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "pi0_steps_sram.png"), dpi=160)
print("\n".join(out))
