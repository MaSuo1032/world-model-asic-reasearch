FAM_STYLE = {   # 3 categorical hues (validated all-pairs) + neutral gray, + marker as 2nd encoding
    "VLA-flow": ("#2a78d6", "o"), "VLA-AR": ("#2a78d6", "^"),
    "WM-JEPA (MPC)": ("#eb6834", "P"), "WM-gen (video DiT)": ("#eb6834", "s"),
    "WM-gen (AR video)": ("#eb6834", "D"),
    "WAM": ("#1baf7a", "*"), "LLM": ("#8a8984", "X"),
}
plt.rcParams.update({"font.size": 9, "axes.edgecolor": INK2, "axes.labelcolor": INK,
                     "xtick.color": INK2, "ytick.color": INK2, "figure.facecolor": SURF,
                     "axes.facecolor": SURF, "savefig.facecolor": SURF})


def style(ax):
    ax.grid(True, color=GRID, lw=0.6, which="major")
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)


# 1) Roofline: stage-level points on H100 + Thor rooflines
fig, ax = plt.subplots(figsize=(10, 6.2))
xs = [10 ** (i / 20) for i in range(-10, 121)]
for hw, ls in ((HW[0], "-"), (HW[2], "--")):
    ax.plot(xs, [min(hw.peak_flops, x * hw.bw) / 1e12 for x in xs], ls, color=INK2, lw=1.4)
    ax.text(2e5, hw.peak_flops / 1e12 * 1.12, hw.name, color=INK2, ha="right")
seen = set()
for w in WORKLOADS:
    c, m = FAM_STYLE[w.family]
    for s in w.bound_breakdown(HW[0], BPW, BPA):
        perf = min(HW[0].peak_flops, s["ai"] * HW[0].bw) / 1e12
        lab = w.family if w.family not in seen else None
        seen.add(w.family)
        ax.scatter(s["ai"], perf, color=c, marker=m, s=(120 if m == "*" else 46), edgecolor=SURF, linewidth=1.2, label=lab, zorder=3)
ax.set_xscale("log"); ax.set_yscale("log")
ax.set_xlim(0.5, 3e5); ax.set_ylim(0.1, 4000)
ax.set_xlabel("Arithmetic intensity of stage (FLOP / byte of DRAM traffic)")
ax.set_ylabel("Attainable TFLOP/s (BF16)")
ax.set_title("Every inference stage on the roofline (each point = one stage of one model)", loc="left", color=INK)
style(ax)
ax.legend(frameon=False, loc="lower right", fontsize=8)
for lbl, x, y in (("LLM decode\n(b=1)", 0.7, 6), ("flow-matching\naction expert", 18, 250),
                  ("ViT / VLM prefill", 420, 1500), ("video DiT / WAM / JEPA-MPC", 2500, 1500)):
    ax.annotate(lbl, (x, y), color=INK2, fontsize=8)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "roofline_stages.png"), dpi=160); plt.close(fig)

# 2) Bytes-per-unit composition (weights / KV+ctx / activations), log x
fig, ax = plt.subplots(figsize=(10, 6.5))
names = [r["workload"] for r in rows][::-1]
wv = [r["weight_GB_per_unit"] for r in rows][::-1]
