for ax, hw in zip(axs, (HW[2], HW[0])):
    lat = [r[f"lat_ms_{hw.name}"] / r["budget_ms"] for r in cand]
    yy = range(len(cand))
    cols = [FAM_STYLE[r["family"]][0] for r in cand]
