"""Run the analytical model for every workload and emit tables + figures.

    python analysis/run_all.py          # writes results/*.csv, results/*.md, figures/*.png
"""
import csv
import math
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from models import WORKLOADS, HW  # noqa: E402
from perf_model import fmt_si  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES, FIG = os.path.join(ROOT, "results"), os.path.join(ROOT, "figures")
os.makedirs(RES, exist_ok=True)
os.makedirs(FIG, exist_ok=True)

BPW, BPA = 2.0, 2.0   # BF16 weights / activations

# ---------------------------------------------------------------- summary table
rows = []
for w in WORKLOADS:
    f, b = w.flops(), w.bytes(BPW, BPA)
    r = dict(
        workload=w.name, family=w.family, unit=w.unit,
        params_B=w.params() / 1e9,
        gflops_per_unit=f / 1e9,
        weight_GB_per_unit=w.weight_bytes(BPW) / 1e9,
        kv_ctx_GB_per_unit=w.kv_bytes(BPA) / 1e9,
        act_GB_per_unit=w.act_bytes(BPA) / 1e9,
        total_GB_per_unit=b / 1e9,
        arith_intensity=f / b,
        weight_share=w.weight_bytes(BPW) / b,
        resident_state_MB=w.resident_state_bytes / 1e6,
        budget_ms=(w.unit_period_s * 1e3) if w.unit_period_s else None,
    )
    for hw in HW:
        r[f"lat_ms_{hw.name}"] = w.roofline_latency(hw, BPW, BPA) * 1e3
    rows.append(r)

with open(os.path.join(RES, "summary.csv"), "w", newline="") as fh:
    wr = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
    wr.writeheader()
    wr.writerows(rows)

# ---------------------------------------------------------------- stage table
stage_rows = []
for w in WORKLOADS:
    for hw in (HW[0], HW[2]):
        for s in w.bound_breakdown(hw, BPW, BPA):
            stage_rows.append(dict(workload=w.name, hw=hw.name, stage=s["stage"],
                                   gflops=s["flops"] / 1e9, MB=s["bytes"] / 1e6,
                                   arith_intensity=s["ai"], bound=s["bound"],
                                   t_ms=s["t"] * 1e3))
with open(os.path.join(RES, "stages.csv"), "w", newline="") as fh:
    wr = csv.DictWriter(fh, fieldnames=list(stage_rows[0].keys()))
    wr.writeheader()
    wr.writerows(stage_rows)


# ---------------------------------------------------------------- markdown
def md_table(header, body):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out)


def n(x, d=1):
    if x is None:
        return "–"
    if x >= 1000:
        return f"{x:,.0f}"
    return f"{x:.{d}f}"


md = ["# Analytical results (auto-generated by analysis/run_all.py)\n",
      "BF16 weights & activations. Latency = ideal roofline lower bound "
      "(sum over passes of max(compute, memory)).\n",
      "## Per-unit totals\n"]
md.append(md_table(
    ["Workload", "Family", "Unit", "Params (B)", "GFLOP/unit", "Weight GB", "KV/ctx GB",
     "Act GB", "AI (FLOP/B)", "Weight share", "Resident state MB", "Budget ms"],
    [[r["workload"], r["family"], r["unit"], n(r["params_B"], 2), n(r["gflops_per_unit"]),
      n(r["weight_GB_per_unit"], 2), n(r["kv_ctx_GB_per_unit"], 3), n(r["act_GB_per_unit"], 2),
      n(r["arith_intensity"]), f'{r["weight_share"]*100:.0f}%', n(r["resident_state_MB"]),
      n(r["budget_ms"])] for r in rows]))
md.append("\n## Roofline latency per unit (ms)\n")
md.append("Ridge points: " + ", ".join(f"{h.name} = {h.ridge:.0f} FLOP/B" for h in HW) + "\n")
md.append(md_table(["Workload", "Budget ms"] + [h.name for h in HW],
                   [[r["workload"], n(r["budget_ms"])] + [n(r[f"lat_ms_{h.name}"]) for h in HW] for r in rows]))
md.append("\n## Stage breakdown (H100 SXM and Jetson AGX Thor)\n")
md.append(md_table(["Workload", "HW", "Stage", "GFLOP", "MB moved", "AI", "Bound", "t (ms)"],
                   [[s["workload"], s["hw"], s["stage"], n(s["gflops"]), n(s["MB"]), n(s["arith_intensity"]),
                     s["bound"], n(s["t_ms"], 2)] for s in stage_rows]))
with open(os.path.join(RES, "results.md"), "w") as fh:
    fh.write("\n".join(md) + "\n")

