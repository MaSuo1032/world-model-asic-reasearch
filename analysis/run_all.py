    ax.set_xscale("log")
    ax.set_title(f"{hw.name}: roofline latency ÷ real-time budget", loc="left", color=INK, fontsize=9)
    for i, v in enumerate(lat):
        ax.text(v * 1.15, i, (f"{v:.2f}×" if v >= 0.01 else f"{v:.4f}×"), va="center", fontsize=7.5, color=INK)
    style(ax); ax.grid(axis="y", visible=False)
