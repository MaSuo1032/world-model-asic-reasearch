"""Combine the exact per-stage counts (flexpi_flops.json) into per-call regimes,
add DRAM traffic, cross-check against the measured RTX 5090 latencies published in
flex-pi/docs/INFERENCE_OPTIMIZATION.md, and project to other hardware.

    python flexpi_regimes.py           # reads ../results/flexpi_flops.json, writes ../results/flexpi_regimes.md
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results")
FIG = os.path.join(HERE, "..", "figures")
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "CLAUDE", "analysis"))  # reuse systolic model

J = json.load(open(os.path.join(RES, "flexpi_flops.json")))
P = J["params"]
G = lambda k: J[k][0]  # noqa: E731  total FLOPs of a stage
BPW = 2.0               # BF16 bytes per weight / activation element

# ---------------- DRAM bytes per stage (weights dominate; KV and activations added) ----------------
N_ANCH, N_ACT, D_V, L, L_INNER = 387, 32, 3072, 30, 16
W_TRUNK = P["visual_trunk_blocks"] * BPW
W_ACT = P["action_expert_blocks"] * BPW
KV_ANCH_ALL = L * N_ANCH * 2 * D_V * BPW            # written by prefill, read by joint decode (all layers)
KV_ANCH_INNER = L_INNER * N_ANCH * 2 * D_V * BPW    # action-only decode reads the 16 inner layers only
B = {
    "encode_vae": P["wan22_vae_encoder"] * BPW,
    "encode_dino": P["dinov3_vitb16"] * BPW,
    "prefill": W_TRUNK + KV_ANCH_ALL,
    "decode_action": W_ACT + KV_ANCH_INNER,
    "decode_joint": W_TRUNK + W_ACT + KV_ANCH_ALL,
}

K = 4  # EVALUATION.num_inference_steps in every shipped eval config
ENC = 2 * G("encode_vae_rgb_first_frame") + G("encode_dino_3cams")   # RGB + pointmap VAE encodes + DINO
ENC_B = 2 * B["encode_vae"] + B["encode_dino"]
REGIMES = {
    # name: list of (stage label, FLOPs, bytes, repeats)
    "action-only (all inputs)": [("encoders", ENC, ENC_B, 1), ("prefill", G("prefill_anchor"), B["prefill"], 1),
                                 ("decode", G("decode_action_only_step"), B["decode_action"], K)],
    "joint RGB": [("encoders", ENC, ENC_B, 1), ("prefill", G("prefill_anchor"), B["prefill"], 1),
                  ("decode", G("decode_joint_rgb_step"), B["decode_joint"], K)],
    "joint RGB+pointmap": [("encoders", ENC, ENC_B, 1), ("prefill", G("prefill_anchor"), B["prefill"], 1),
                           ("decode", G("decode_joint_rgb_pointmap_step"), B["decode_joint"], K)],
    "joint full (KV-split)": [("encoders", ENC, ENC_B, 1), ("prefill", G("prefill_anchor"), B["prefill"], 1),
                              ("decode", G("decode_joint_full_step"), B["decode_joint"], K)],
    "joint full (no anchor cache)": [("encoders", ENC, ENC_B, 1),
                                     ("decode+anchors", G("decode_joint_full_step") + G("prefill_anchor"),
                                      B["decode_joint"], K)],
}
MEASURED_5090 = {  # docs/INFERENCE_OPTIMIZATION.md, ms/call at 4 steps
    "action-only (all inputs)": {"torch.compile": 60, "eager": 132},
    "joint full (KV-split)": {"TensorRT KV-split": 193},
    "joint full (no anchor cache)": {"eager": 447, "torch.compile": 360, "TensorRT single engine": 230},
}
HW = {  # name: (peak BF16 FLOP/s dense, DRAM B/s)
    "RTX 5090": (209e12, 1.792e12),
    "Jetson AGX Thor*": (259e12, 273e9),
    "H100 SXM": (989e12, 3.35e12),
}


def latency(stages, hw):
    pk, bw = HW[hw]
    rows = [(lbl, f, b, r, max(f / pk, b / bw) * r, "compute" if f / pk >= b / bw else "memory")
            for lbl, f, b, r in stages]
    return sum(x[4] for x in rows), rows


out = ["# Flex-π inference regimes (auto-generated by flexpi_regimes.py)\n",
       "FLOPs counted on the official model code (meta device, `flexpi_flops.py`); bytes = BF16 weights + anchor "
       "K/V. Latency = ideal roofline (sum over stages of max(FLOPs/peak, bytes/BW)). *Thor BF16 peak is a derived "
       "estimate (see CLAUDE/docs/00).\n",
       "## Per-call totals\n",
       "| Regime | GFLOP / call | GB moved / call | 5090 ideal ms | measured 5090 ms | ideal ÷ measured | Thor* ideal ms | H100 ideal ms |",
       "|---|---|---|---|---|---|---|---|"]
summary = {}
for name, st in REGIMES.items():
    f = sum(s[1] * s[3] for s in st)
    b = sum(s[2] * s[3] for s in st)
    t5, _ = latency(st, "RTX 5090")
    tt, _ = latency(st, "Jetson AGX Thor*")
    th, _ = latency(st, "H100 SXM")
    meas = MEASURED_5090.get(name, {})
    mtxt = ", ".join(f"{v} ({k})" for k, v in meas.items()) or "–"
    best = min(meas.values()) if meas else None
    eff = f"{t5 * 1e3 / best * 100:.0f}%" if best else "–"
    summary[name] = dict(gflop=f / 1e9, gb=b / 1e9, t5090=t5 * 1e3, tthor=tt * 1e3, th100=th * 1e3)
    out.append(f"| {name} | {f/1e9:,.0f} | {b/1e9:.1f} | {t5*1e3:.1f} | {mtxt} | {eff} | {tt*1e3:.1f} | {th*1e3:.1f} |")

out.append("\n## Stage breakdown (RTX 5090 and Thor*)\n")
out.append("| Regime | Stage | GFLOP each | GB each | × | arithmetic intensity (FLOP/B) | 5090: bound, ms | Thor*: bound, ms |")
out.append("|---|---|---|---|---|---|---|---|")
for name, st in REGIMES.items():
    _, r5 = latency(st, "RTX 5090")
    _, rt = latency(st, "Jetson AGX Thor*")
    for (lbl, f, b, rep, t5, b5), (_, _, _, _, tt, bt) in zip(r5, rt):
        out.append(f"| {name} | {lbl} | {f/1e9:,.1f} | {b/1e9:.2f} | {rep} | {f/b:,.0f} | {b5}, {t5*1e3:.1f} | {bt}, {tt*1e3:.1f} |")

# ---------------- systolic utilization of Flex-π GEMM shapes (CLAUDE round-3 model) ----------------
try:
    import systolic as S
    S.fit_coeffs(os.path.join(HERE, "..", "..", "..", "CLAUDE", "results", "scalesim_validation.csv"))
    tg = S.transformer_gemms
    stages = {
        "prefill: 387 anchors × 5B trunk": tg(387, 387, 3072, 24, 128, 24, 14336, 30, gated=False, cross_layers=30,
                                               n_ctx=129),
        "decode action-only: 32 tokens × 1B expert": tg(32, 419, 1024, 24, 128, 24, 4096, 30, gated=False,
                                                        cross_layers=30, n_ctx=129),
        "decode joint full: 774 tokens × 5B trunk": tg(774, 1193, 3072, 24, 128, 24, 14336, 30, gated=False,
                                                       cross_layers=30, n_ctx=129),
    }
    out.append("\n## Systolic-array utilization of Flex-π's GEMM shapes (16,384 MACs, SCALE-Sim-calibrated model)\n")
    out.append("| Stage | 1× 128×128 WS | 1× 128×128 OS | 16× 32×32 OS | 16× 32×32 per-GEMM best |")
    out.append("|---|---|---|---|---|")
    for sname, g in stages.items():
        u = [S.stage_util(g, 128, 128, "ws", 1)[1], S.stage_util(g, 128, 128, "os", 1)[1],
             S.stage_util(g, 32, 32, "os", 16)[1], S.best_df(g, 32, 32, 16)[1]]
        out.append(f"| {sname} | " + " | ".join(f"{x*100:.0f}%" for x in u) + " |")
except Exception as e:  # noqa: BLE001
    out.append(f"\n(systolic section skipped: {e})\n")

os.makedirs(RES, exist_ok=True)
open(os.path.join(RES, "flexpi_regimes.md"), "w").write("\n".join(out) + "\n")
json.dump(summary, open(os.path.join(RES, "flexpi_regimes.json"), "w"), indent=1)
print("\n".join(out))

# ---------------- figure ----------------
import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
PAL = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6"]
fig, (a1, a2) = plt.subplots(1, 2, figsize=(14, 5.4), facecolor=SURF, gridspec_kw={"width_ratios": [1.05, 1]})
for ax in (a1, a2):
    ax.set_facecolor(SURF)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)

# left: what the FLOPs are, per stage
cats = [("ffn", "FFN (MLP)"), ("self_attn_qkvo", "self-attn Q/K/V/O proj."), ("cross_attn_q_o", "cross-attn Q/O proj."),
        ("cross_attn_kv_on_text", "cross-attn K/V on text (re-done every step)"),
        ("attention_scores_sdpa", "attention scores (QKᵀ, PV)"), ("conv", "3D conv (VAE)"), ("other_linear", "other linear (ViT)")]
stg = [("prefill_anchor", "prefill (387 anchors, 5B)"), ("decode_action_only_step", "decode action-only / step"),
       ("decode_joint_full_step", "decode joint full / step"), ("encode_vae_rgb_first_frame", "VAE encode (1 frame)"),
       ("encode_dino_3cams", "DINOv3 encode (3 cams)")]
for i, (k, lab) in enumerate(stg):
    tot, by = J[k][0], J[k][1]
    left = 0
    for j, (c, _) in enumerate(cats):
        v = by.get(c, 0) / tot
        if v > 0:
            a1.barh(i, v, left=left, color=PAL[j], height=0.62, edgecolor=SURF, linewidth=2)
            if v > 0.06:
                a1.text(left + v / 2, i, f"{v*100:.0f}%", ha="center", va="center", fontsize=7.5, color="white")
            left += v
    a1.text(1.02, i, f"{tot/1e9:,.0f} GFLOP", va="center", fontsize=8, color=INK)
a1.set_yticks(range(len(stg)))
a1.set_yticklabels([s[1] for s in stg], fontsize=8.5)
a1.invert_yaxis()
a1.set_xlim(0, 1.22)
a1.set_xticks([0, .25, .5, .75, 1])
a1.set_xticklabels(["0%", "25%", "50%", "75%", "100%"], fontsize=8)
a1.set_title("Q1 · Where Flex-π's FLOPs go (counted on official code)", loc="left", fontsize=10, color=INK)
from matplotlib.patches import Patch  # noqa: E402
a1.legend(handles=[Patch(color=PAL[j], label=l) for j, (_, l) in enumerate(cats)], fontsize=7.5, frameon=False,
          loc="upper center", bbox_to_anchor=(0.45, -0.08), ncol=2)

# right: per-regime ideal latency on RTX 5090, stacked by stage, with measured latency markers
names = ["action-only (all inputs)", "joint RGB", "joint RGB+pointmap", "joint full (KV-split)"]
for i, n in enumerate(names):
    _, rows = latency(REGIMES[n], "RTX 5090")
    left = 0
    for j, (lbl, _f, _b, _r, tms, _bd) in enumerate(rows):
        a2.barh(i, tms * 1e3, left=left, color=PAL[j], height=0.62, edgecolor=SURF, linewidth=2)
        left += tms * 1e3
    if left > 45:
        a2.text(left - 2, i, f"ideal {left:.0f} ms", va="center", ha="right", fontsize=8, color="white",
                fontweight="bold")
    else:
        a2.text(left + 2, i - 0.2, f"ideal {left:.0f} ms", va="center", ha="left", fontsize=8, color=INK,
                fontweight="bold")
    for k, (stack, v) in enumerate(MEASURED_5090.get(n, {}).items()):
        a2.plot([v], [i], marker="D", ms=8, color=INK, mec=SURF, mew=1.5, zorder=3)
        short = {"torch.compile": "compile", "eager": "eager", "TensorRT KV-split": "TRT KV-split"}.get(stack, stack)
        a2.text(v, i + 0.36, f"{v} ms\n{short}", ha="center", va="top", fontsize=7.2, color=INK2)
a2.set_yticks(range(len(names)))
a2.set_yticklabels(names, fontsize=8.5)
a2.invert_yaxis()
a2.set_xlim(0, 300)
a2.set_xlabel("ms per call, RTX 5090 (BF16 209 TFLOP/s, 1.79 TB/s), K = 4 steps", fontsize=8.5)
a2.grid(axis="x", color=GRID, lw=0.6)
a2.plot([], [], "D", color=INK, ms=7, label="measured (official, RTX 5090)")
a2.legend(handles=[Patch(color=PAL[0], label="encoders (VAE×2 + DINOv3)"), Patch(color=PAL[1], label="prefill (once)"),
                   Patch(color=PAL[2], label="decode (×4 steps)"),
                   plt.Line2D([], [], marker="D", ls="", color=INK, label="measured (official, RTX 5090)")], fontsize=7.5, frameon=False, loc="upper right",
           bbox_to_anchor=(1.0, 1.0))
a2.set_title("Q3 · Ideal roofline vs. measured latency per regime", loc="left", fontsize=10, color=INK)
fig.tight_layout()
